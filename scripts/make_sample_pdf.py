"""生成一份最小的示例 PDF，用来测试上传接口。

别人的项目常常把测试用的二进制文件直接塞进仓库；这里改成"用脚本生成"，
好处是文件怎么来的、内容是什么都写得清清楚楚，也方便改。

用法：
    .\\.venv\\Scripts\\python.exe scripts\\make_sample_pdf.py
产物：
    examples/sample.pdf
"""

from __future__ import annotations

from pathlib import Path


def build_pdf(lines: list[str]) -> bytes:
    """手工拼一个最小可用的 PDF（一页，Helvetica 字体，纯 ASCII 文字）。"""
    content_parts = ["BT", "/F1 14 Tf", "30 150 Td", "16 TL"]
    for line in lines:
        escaped = line.replace("(", r"\(").replace(")", r"\)")
        content_parts.append(f"({escaped}) Tj T*")
    content_parts.append("ET")
    content = "\n".join(content_parts).encode("latin-1")

    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 400 220] "
        b"/Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
        b"<< /Length " + str(len(content)).encode() + b" >>\nstream\n" + content + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]

    out = bytearray(b"%PDF-1.4\n")
    offsets: list[int] = []
    for index, obj in enumerate(objects, 1):
        offsets.append(len(out))
        out += f"{index} 0 obj\n".encode() + obj + b"\nendobj\n"

    # PDF 的交叉引用表：记录每个对象在文件里的字节偏移，解析器靠它快速定位
    xref_pos = len(out)
    out += f"xref\n0 {len(objects) + 1}\n".encode()
    out += b"0000000000 65535 f \n"
    for offset in offsets:
        out += f"{offset:010d} 00000 n \n".encode()
    out += (
        b"trailer\n<< /Size " + str(len(objects) + 1).encode() + b" /Root 1 0 R >>\n"
        b"startxref\n" + str(xref_pos).encode() + b"\n%%EOF\n"
    )
    return bytes(out)


def main() -> None:
    pdf_bytes = build_pdf(
        [
            "DocuMind sample PDF",
            "This page is generated by scripts/make_sample_pdf.py",
            "The vector retrieval baseline stores embeddings as float32 blobs.",
            "BM25 ranks documents by term frequency saturation and length normalization.",
        ]
    )
    target = Path(__file__).resolve().parent.parent / "examples" / "sample.pdf"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(pdf_bytes)
    print(f"已生成 {target}（{len(pdf_bytes)} 字节）")


if __name__ == "__main__":
    main()
